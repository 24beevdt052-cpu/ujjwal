def _sheets(counts: Counts, ctx: dict) -> list[str]:
    rows = []
    for name, part, what in sheet_readme.SHEET_MAP:
        c = counts.per_sheet.get(name, {})
        total = sum(c.values())
        rows.append([f"`{name}`", part, f"{c.get(FORMULA, 0):,}", f"{counts.ratio(name):.0%}" if total else "—",
                     what])
    return ["## 3. Sheet by sheet", "",
            _table(["Sheet", "Part", "Formula cells", "Formula share", "What it is"], rows), "",
            "The formula share is formula cells ÷ all written cells on the sheet, counting row keys, labels, "
            "provenance strings and green check columns in the denominator. A sheet that is mostly a register "
            "(`Inputs`, `Counterparties`, `Trade_Book`) is *supposed* to be mostly input.", ""]


def _coverage(counts: Counts, ctx: dict) -> list[str]:
    rows = []
    tot = {INPUT: 0, FORMULA: 0, PASTED: 0, KEY: 0}
    for name in [s[0] for s in sheet_readme.SHEET_MAP]:
        c = counts.per_sheet.get(name, {})
        for k in tot:
            tot[k] += c.get(k, 0)
        rows.append([f"`{name}`", f"{c.get(FORMULA, 0):,}", f"{c.get(INPUT, 0):,}", f"{c.get(PASTED, 0):,}",
                     f"{c.get(KEY, 0):,}", f"{sum(c.values()):,}"])
    rows.append(["**Total**", f"**{tot[FORMULA]:,}**", f"**{tot[INPUT]:,}**", f"**{tot[PASTED]:,}**",
                 f"**{tot[KEY]:,}**", f"**{sum(tot.values()):,}**"])
    total = sum(tot.values())
    share = tot[FORMULA] / total if total else 0.0
    return ["## 4. Formula coverage", "",
            _table(["Sheet", "formula", "input (blue)", "pasted (green)", "key / label", "total"], rows), "",
            f"**{tot[FORMULA]:,} formula cells of {total:,} written cells ({share:.0%})**, against "
            f"{tot[INPUT]:,} inputs and {tot[PASTED]:,} pasted engine values. Of the pasted cells, roughly half are "
            "pure check columns that nothing depends on; the rest are the carried lifecycle amounts named in §7.", ""]


