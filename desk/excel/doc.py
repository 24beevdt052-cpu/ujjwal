def _checks(ctx: dict) -> list[str]:
    rows = [[b["family"], f"{b['n']:,}", b["tolerance"]] for b in ctx["checks"]["blocks"]]
    return ["## 6. The Checks sheet", "",
            _table(["Check family", "Rows", "Tolerance"], rows), "",
            "Each row of each block pastes the engine's value (green), references the workbook's own formula cell, "
            "shows the difference and raises a PASS/FAIL against a tolerance held as a named range on `Inputs`. "
            "The two tolerances the brief fixes are `tol_parity_inr_t` = ₹1 per tonne on every parity line and "
            "`tol_trade_inr` = ₹10 per trade on MTM and cumulative P&L. The others exist because the *published "
            "CSV* rounds: `amount_ccy` to 2 dp (so a re-derived INR amount cannot tie closer than about ₹0.75), "
            "and USD/t and ₹/kg to 4 dp.", "",
            "One control is deliberately indirect and is stated as such on the sheet: the Phase 1 ↔ Phase 3 "
            "replacement-value tie (`R = goods + bcd + sws + port` on every parity **value date**) cannot be made "
            "in the workbook, because the marking grid is month-ends and those are not parity value dates. The "
            "chain is workbook `replacement_inr_t` ↔ engine `px_inr_t` (checked on every `INVENTORY` row here) ↔ "
            "Phase 1 (checked in `pnl_controls.csv`).", ""]


def _recon() -> list[str]:
    head = ["## 7. Reconciliation test", "",
            "`tests/test_excel_reconciliation.py` loads the saved workbook with the `formulas` library and "
            "**recalculates it from the formulas alone**. There is nothing else it could do: openpyxl writes "
            "formulas without cached results, and one of the tests opens the saved zip and asserts that no `<f>` "
            "element is followed by a cached `<v>`. It then asserts four things:", "",
            "1. every `check` cell recalculates to PASS, and so does the scoreboard formula that aggregates them;",
            "2. the computed sheets really are computed — a formula-vs-constant census per sheet against a floor "
            "per sheet, so a later edit cannot quietly swap a formula for a pasted number;",
            "3. no cell recalculates to `#REF!`, `#NAME?`, `#DIV/0!`, `#VALUE!`, `#N/A`, `#NULL!` or `#NUM!`;",
            "4. the workbook is byte-for-byte deterministic (CONTRACTS §1.5) — rebuilding it produces an identical "
            "file, which is why the zip entry timestamps and the document properties are pinned.", ""]
    if not RECON_JSON.exists():
        return head + ["_No reconciliation run has been recorded yet. Run "
                       "`DESK_OFFLINE=1 .venv/bin/python -m pytest -q tests/test_excel_reconciliation.py` and "
                       "re-run `desk.excel.build` to fill this section._", ""]
    r = json.loads(RECON_JSON.read_text())
    rows = [[f"`{k}`", f"{v['formula']:,}", f"{v['constant']:,}", f"{v['ratio']:.0%}"]
            for k, v in sorted(r["sheets"].items())]
    scope = r.get("scope", "full workbook")
    return head + [
        f"**Scope of the recalculation: {scope}.** {r.get('scope_note', '')}", "",
        f"* cells recalculated: **{r['n_recalculated']:,}**  ·  wall time **{r['seconds']:.0f} s**",
        f"* `Checks` cells read: **{r['n_check_cells']:,}**, failures: **{r['n_check_failures']}**",
        f"* scoreboard verdict recalculated from the formulas: **{r['scoreboard']}**",
        f"* error values after recalculation (`#REF!` / `#NAME?` / `#DIV/0!` / `#VALUE!` / `#N/A`): "
        f"**{r['n_errors']}**", "",
        "Formula-vs-constant census of the written cells in the saved file (openpyxl read-back, independent of the "
        "recalculation):", "",
        _table(["Sheet", "formula cells", "constant cells", "formula share"], rows), "",
        "Worst absolute differences the recalculated workbook reports, by family:", "",
        _table(["Check family", "max |difference|", "tolerance", "status"],
               [[k, f"{v['max_abs_diff']:,.4f}", v["tolerance"], v["status"]] for k, v in r["families"].items()]),
        "",
    ]


def _not_in_excel() -> list[str]:
    rows = [[a, b] for a, b in _NOT_IN_EXCEL]
    return ["## 8. What stays in Python, and why", "",
            _table(["Left in Python", "Why"], rows), "",
            "Two of these deserve the longer answer.", "",
            "**The attribution chain.** The engine splits each day's P&L by fully revaluing every leg of every "
            "ticket eight times — once for each `FACTOR_ORDER` block, then for the contracts block — from "
            "yesterday's state to today's, so that cross-terms land in the factor that moves last and the residual "
            "is a genuine control rather than a plug. Reproducing that in cells would mean eight copies of the "
            "whole lifecycle expansion per trade-day. `Attribution` §3a and §3b instead work the chain in full on "
            "two legs whose value is closed form — a short MCX hedge across the day the LME broke from its "
            "all-time high, and a USD payable against the forward that hedges it — and check each step against "
            "`desk.mtm.curves` directly. That shows the mechanism honestly and proves the arithmetic; it does not "
            "claim to be the whole engine.", "",
            "**Leg amounts from the ticket lifecycle.** A purchase invoice on an `LME_M1_AVG` formula is the mean of "
            "the official cash price over the panel days of a quotational month; a quality claim depends on a "
            "survey outcome and a penalty schedule; demurrage counts calendar days of dwell past a free period; an "
            "LC fee runs on a validity computed from a laycan and a presentation period. These are "
            "date-and-contract computations on a rolled panel calendar, not market arithmetic — which is why the "
            "workbook carries the amount and derives everything the *market* does to it (the FX conversion to "
            "settle date, the aggregation into cumulative P&L).", ""]


