def _limitations(data: sources.Data) -> list[str]:
    return ["## 9. Limitations and open issues", "",
            "1. **The marking grid is not every day.** Leg-level marks exist on "
            f"{len(data.mark_dates)} dates, not on all {data.attribution['date'].nunique()} book days. The "
            "`Equity_Curve` carries the engine's daily open-MTM and re-derives it from `MTM_Daily` only where the "
            "grid reaches; the difference column shows both. Per-trade cumulative P&L is reconciled at "
            "`WINDOW_END` and `HORIZON_END` as the brief requires.",
            "2. **Green cells that feed forward.** The colour convention would be cleaner if nothing downstream "
            "ever depended on a pasted value. It does not hold for the carried lifecycle amounts, so those rows "
            "carry an explicit `amount_src` / `value_src` column rather than relying on the reader to remember.",
            "3. **Rounding floors three of the tolerances.** The workbook reads the published CSVs, which are "
            "rounded for determinism (₹0.01 on money, 4 dp on prices). `tol_cashflow_inr`, `tol_usd_t` and part of "
            "`tol_grid_inr` exist only because of that; `Checks` says so row by row, and the observed differences "
            "sit one to three orders of magnitude inside every tolerance.",
            "4. **Phase 3 book parameters are still served from code.** `config/params/book.yaml` does not exist; "
            "`Inputs` §4 lists the eleven keys the workbook uses from "
            "`desk.mtm.constants.BOOK_PARAM_FALLBACKS`, with their flags and verification status, separately from "
            "the register so the two can never be confused. Three of them carry PENDING verification.",
            "5. **Recalculation is slow outside Excel.** Excel itself recalculates the file instantly; the "
            "`formulas` library takes minutes because it builds an explicit dependency graph over every cell. The "
            "reconciliation test therefore runs as one long test and reports its own wall time.",
            "6. **The workbook inherits every Phase 0 caveat.** Freight levels and the lag-2 grade mix are "
            "hindsight reconstructions; USD/INR is an ECB cross, PENDING a measured comparison against FBIL; the "
            "MCX panel series is import parity, so bucket (b) is zero by construction and the mirror run — which "
            "is the only way to see a real cross-exchange basis — is a Python sensitivity, not a workbook sheet.",
            ""]
